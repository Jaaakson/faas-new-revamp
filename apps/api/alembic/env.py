"""Alembic environment.

The database URL comes from application settings, never from alembic.ini, so
there is exactly one place a connection string is configured.

Every model module must be imported here for autogenerate to see it. A model
that is not imported is silently invisible to autogenerate, which produces a
migration that drops nothing and creates nothing — the most confusing failure
mode Alembic has.
"""

from __future__ import annotations

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from app.core.config import settings
from app.shared.base_model import Base

# ── Model imports for autogenerate ────────────────────────────────────────────
# Every model module must be imported here. A model that is not imported is
# invisible to autogenerate, which silently produces an empty migration.
from app.modules.auth import models as auth_models  # noqa: F401, E402
from app.modules.biometrics import models as biometrics_models  # noqa: F401, E402
from app.modules.identity import models as identity_models  # noqa: F401, E402

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

config.set_main_option("sqlalchemy.url", settings.DATABASE_URL)

target_metadata = Base.metadata


def _include_object(object_, name, type_, reflected, compare_to) -> bool:  # type: ignore[no-untyped-def]
    """Keep extension-owned objects out of autogenerated diffs.

    pgvector and citext create types and tables we do not manage; without this
    filter, autogenerate proposes dropping them on every run.
    """
    if type_ == "table" and name in {"spatial_ref_sys"}:
        return False
    return True


def run_migrations_offline() -> None:
    """Emit SQL without a live connection (`alembic upgrade head --sql`)."""
    context.configure(
        url=settings.DATABASE_URL,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
        include_object=_include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


def _do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        compare_type=True,
        compare_server_default=True,
        include_object=_include_object,
        # Wrap DDL in a transaction so a failed migration leaves no partial state.
        transaction_per_migration=True,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(_do_run_migrations)
    await connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
